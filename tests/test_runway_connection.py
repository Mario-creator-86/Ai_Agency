def connect(client, headers, name="Studio video account"):
    identifier = str(uuid4())
    response = client.put(
        f"/api/v1/settings/integrations/{identifier}",
        headers=headers,
        json={"kind": "runway", "name": name, "secrets": {"api_key": f"test-key-{uuid4()}"}},
    )
    return identifier, response


def settings_view(client, headers):
    return client.get("/api/v1/settings", headers=headers).json()


def test_form_needs_only_a_name_and_a_key_and_discovers_the_accounts_video_models(
    client, headers, engine, runway_api
):
    spec = settings_view(client, headers)["catalog"]["runway"]
    # The key is what the connection needs; the credit price is optional and the Owner's,
    # and without it a film's cost is reported in credits rather than guessed in dollars.
    assert [field["key"] for field in spec["fields"]] == ["api_key", "credit_usd"]
    assert [f["required"] for f in spec["fields"]] == [True, False]
    assert spec["runtime"] == "media" and spec["purposes"] == ["video", "image"]

    identifier, response = connect(client, headers)
    assert response.status_code == 200, response.text
    saved = response.json()
    assert saved["status"] == "VERIFIED" and saved["config"] == {}
    assert saved["message"].startswith("Conexiune verificată.")
    catalog = saved["catalog"]
    assert catalog["kind_info"]["model_label"] == "Model video implicit"
    assert catalog["kind_info"]["has_voices"] is False and catalog["voices"] == []
    by_id = {m["remote_id"]: m for m in catalog["models"]}
    assert set(by_id) == set(runway_api.models)
    first = runway_api.video_models[0]
    assert by_id[first]["production_usable"] is True
    assert by_id[first]["api_metadata"]["tasks"] == ["image_to_video", "text_to_video"]
    assert by_id[first]["api_metadata"]["ratios"]["text_to_video"] == ["1280:720", "720:1280"]
    assert by_id[first]["api_metadata"]["durations"]["text_to_video"] == [5, 10]
    limits = runway_api.models[first]
    assert by_id[first]["api_metadata"]["max_daily_generations"] == limits["maxDailyGenerations"]
    assert by_id[first]["api_metadata"]["daily_generations"] == 2
    # The account has an image model too: listed, usable for stills, never for video.
    assert by_id[runway_api.image_model]["usable_purposes"] == ["image"]
    assert by_id[first]["usable_purposes"] == ["video"]
    assert catalog["production"] == {
        "model_id": None,
        "voice_id": None,
        "image_model_id": None,
        "allow_production_override": True,
        "version": 0,
    }
    assert "test-key-" not in json.dumps(saved)
    assert ("api.dev.runwayml.com", "GET", "/v1/organization") in runway_api.calls
    assert ("docs.dev.runwayml.com", "GET", "/openapi.json") in runway_api.calls
    assert identifier in settings_view(client, headers)["provider_catalogs"]
    with Session(engine) as session:
        rows = session.scalars(
            select(ProviderResource).where(ProviderResource.integration_id == identifier)
        ).all()
        assert {r.resource_type for r in rows} == {"MODEL"} and len(rows) == len(runway_api.models)


def test_check_refreshes_and_a_model_the_account_lost_becomes_unavailable(
    client, headers, runway_api
):
    identifier, _ = connect(client, headers)
    lost = runway_api.video_models[1]
    del runway_api.models[lost]
    checked = client.post(
        f"/api/v1/settings/integrations/{identifier}/check", headers=headers
    ).json()
    assert checked["status"] == "VERIFIED"
    models = {
        m["remote_id"]: m
        for m in settings_view(client, headers)["provider_catalogs"][identifier]["models"]
    }
    assert models[lost]["available"] is False and models[lost]["production_usable"] is False
    assert models[runway_api.video_models[0]]["available"] is True


