def test_a_model_that_needs_reference_images_is_neither_chosen_nor_called(engine):
    """gen4_image_turbo is listed under text_to_image and requires reference images: the
    cheapest still model in the account, chosen by price, answered HTTP 400 to every scene
    of a day. The contract says so per model, so the choice skips it and the adapter refuses
    before spending a call."""
    from app.integrations.discovery import usable_purposes
    from app.media.production_policy import rank_candidates
    from app.providers.runway import RunwayImageAdapter
    from app.services import append_event, utc_now

    integration_id = str(uuid4())
    vault = CredentialVault(Path(str(engine.url.database)).with_suffix(".credentials.key"))
    with Session(engine) as session, session.begin():
        event = append_event(
            session,
            "settings.integration_saved",
            "integration",
            integration_id,
            1,
            {},
            str(uuid4()),
        )
        session.add(
            Integration(
                id=integration_id,
                kind="runway",
                name="runway",
                config={},
                encrypted_secrets=vault.encrypt({"api_key": "k"}),
                secret_fields=["api_key"],
                version=1,
                status="ACCESS_VERIFIED",
                checked_at=None,
                event_id=event.event_id,
            )
        )
        session.flush()
        for remote_id, needs, price in (
            ("editing_only", True, 0.015),
            ("draws_from_words", False, 0.02),
        ):
            session.add(
                ProviderResource(
                    id=str(uuid4()),
                    integration_id=integration_id,
                    resource_type="MODEL",
                    remote_id=remote_id,
                    name=remote_id,
                    api_metadata={
                        "tasks": ["text_to_image"],
                        "ratios": {"text_to_image": ["1080:1920"]},
                        "needs_references": {"text_to_image": needs},
                    },
                    api_available=True,
                    last_seen_at=utc_now(),
                    pricing={"per_image_usd": price, "unit": "per image"},
                    capabilities={},
                    metadata_version=1,
                )
            )

    with Session(engine) as session:
        ranked = [
            c["remote_id"] for c in rank_candidates(session, integration_id, "MODEL", None, "image")
        ]
    # The cheaper one is the editing model; it is not a candidate for a still from a prompt,
    # and the API's own evidence says it serves no purpose the studio has.
    assert ranked == ["draws_from_words"]
    with Session(engine) as session:
        by_id = {
            row.remote_id: row
            for row in session.scalars(
                select(ProviderResource).where(ProviderResource.integration_id == integration_id)
            )
        }
        assert usable_purposes("runway", by_id["editing_only"]) == []
        assert usable_purposes("runway", by_id["draws_from_words"]) == ["image"]
        # The stored default becomes unusable, so nothing renders through it by accident.
        assert (
            production_resource(session, integration_id, "MODEL", "editing_only", "image") is None
        )

    adapter = RunwayImageAdapter(
        api_key="k",
        model="editing_only",
        model_metadata={
            "tasks": ["text_to_image"],
            "ratios": {"text_to_image": ["1080:1920"]},
            "needs_references": {"text_to_image": True},
        },
    )
    with pytest.raises(MediaProviderError) as excinfo:
        asyncio.run(adapter.generate_image("a starry sky"))
    assert excinfo.value.code == "reference_images_required"
    assert "needs reference images" in str(excinfo.value)


def test_auto_configure_replaces_a_default_the_api_no_longer_supports(engine, monkeypatch):
    """The Owner's stored image default was an editing model; the studio kept it because a
    default existed, and every render refused. A default the API's own evidence cannot
    support is replaced, and the reason names the model that was dropped."""
    from app.integrations.autoconfig import auto_configure
    from app.integrations.models import MediaProductionConfig
    from app.integrations.services import select_service
    from app.services import append_event, utc_now

    integration_id = str(uuid4())
    vault = CredentialVault(Path(str(engine.url.database)).with_suffix(".credentials.key"))
    with Session(engine) as session, session.begin():
        event = append_event(
            session,
            "settings.integration_saved",
            "integration",
            integration_id,
            1,
            {},
            str(uuid4()),
        )
        session.add(
            Integration(
                id=integration_id,
                kind="runway",
                name="runway",
                config={},
                encrypted_secrets=vault.encrypt({"api_key": "k"}),
                secret_fields=["api_key"],
                version=1,
                status="VERIFIED",
                checked_at=utc_now(),
                event_id=event.event_id,
            )
        )
        session.flush()
        for remote_id, needs, tasks in (
            ("editing_only", True, ["text_to_image"]),
            ("draws_from_words", False, ["text_to_image"]),
            ("makes_video", False, ["text_to_video"]),
        ):
            session.add(
                ProviderResource(
                    id=str(uuid4()),
                    integration_id=integration_id,
                    resource_type="MODEL",
                    remote_id=remote_id,
                    name=remote_id,
                    api_metadata={
                        "tasks": tasks,
                        "ratios": {tasks[0]: ["1080:1920"]},
                        "needs_references": {tasks[0]: needs},
                    },
                    api_available=True,
                    last_seen_at=utc_now(),
                    pricing={},
                    capabilities={},
                    metadata_version=1,
                )
            )
    for purpose in ("image", "video"):
        select_service(engine, purpose, integration_id, 0)
    # The Owner's stored defaults, written before the contract was understood.
    with Session(engine) as session, session.begin():
        session.add(
            MediaProductionConfig(
                integration_id=integration_id,
                model_id="makes_video",
                voice_id=None,
                image_model_id="editing_only",
                version=1,
                updated_at=utc_now(),
                allow_production_override=True,
            )
        )

    result = auto_configure(engine, vault)

    applied = [a for a in result["applied"] if a["connection"] == "runway"]
    assert applied and "image: draws_from_words" in applied[0]["why"]
    assert "editing_only" in applied[0]["why"]
    with Session(engine) as session:
        config = session.get(MediaProductionConfig, integration_id)
        assert config.image_model_id == "draws_from_words"
        assert config.model_id == "makes_video"  # a usable default is left alone


