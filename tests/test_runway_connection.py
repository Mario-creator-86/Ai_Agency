def test_unreadable_contract_keeps_models_but_leaves_capabilities_to_research(
    client, headers, runway_api
):
    runway_api.spec_fail = True
    identifier, response = connect(client, headers)
    body = response.json()
    assert body["status"] == "VERIFIED" and "Contractul API Runway" in body["message"]
    models = {m["remote_id"]: m for m in body["catalog"]["models"]}
    assert set(models) == set(runway_api.models)
    assert "tasks" not in models[runway_api.video_models[0]]["api_metadata"]
    assert all(m["production_usable"] is False for m in models.values())
    # Research may state what the API did not; it never invents availability.
    patched = client.patch(
        f"/api/v1/settings/resources/{models[runway_api.video_models[0]]['id']}/metadata",
        headers=headers,
        json={
            "expected_version": 0,
            "capabilities": {"tasks": ["text_to_video"]},
            "source": "Runway API reference, read by hand",
        },
    )
    assert patched.status_code == 200, patched.text
    assert patched.json()["production_usable"] is True
    assert identifier in settings_view(client, headers)["provider_catalogs"]


def test_default_video_model_is_optional_and_must_be_a_discovered_video_model(
    client, headers, engine, runway_api
):
    identifier, _ = connect(client, headers)
    path = f"/api/v1/settings/integrations/{identifier}/production"
    for wrong in (
        {"model_id": "gen-imagined"},
        {"model_id": runway_api.image_model},
        {"model_id": runway_api.video_models[0], "voice_id": "no-voices-here"},
    ):
        response = client.put(path, headers=headers, json={**wrong, "expected_version": 0})
        assert response.status_code == 422, wrong
    # No default at all is a valid state: production then chooses per video.
    assert client.put(path, headers=headers, json={"expected_version": 0}).status_code == 200
    saved = client.put(
        path,
        headers=headers,
        json={"model_id": runway_api.video_models[0], "expected_version": 1},
    )
    assert saved.status_code == 200, saved.text
    catalog = settings_view(client, headers)["provider_catalogs"][identifier]
    assert catalog["production"]["model_id"] == runway_api.video_models[0]
    assert catalog["production"]["allow_production_override"] is True
    with Session(engine) as session:
        assert session.get(Integration, identifier).config == {}


def test_video_adapter_is_built_only_for_a_discovered_video_model_and_carries_its_contract(
    client, headers, engine, runway_api
):
    identifier, _ = connect(client, headers)
    vault = CredentialVault(Path(str(engine.url.database)).with_suffix(".credentials.key"))
    model = runway_api.video_models[0]
    adapter = video_provider_for(
        engine, vault, {"valid": True, "integration_id": identifier, "model_id": model}
    )
    assert isinstance(adapter, RunwayVideoAdapter) and adapter.model == model
    assert adapter.model_metadata["ratios"]["text_to_video"] == ["1280:720", "720:1280"]
    for resolved in (
        {"valid": False, "integration_id": identifier, "model_id": model},
        {"valid": True, "integration_id": identifier, "model_id": runway_api.image_model},
        {"valid": True, "integration_id": identifier, "model_id": None},
    ):
        assert video_provider_for(engine, vault, resolved) is None, resolved


def test_generation_follows_the_contract_and_polls_the_task(runway_api):
    model = runway_api.video_models[0]
    adapter = RunwayVideoAdapter(
        "test-key",  # pragma: allowlist secret
        model,
        {
            "tasks": ["text_to_video"],
            "ratios": {"text_to_video": ["1280:720", "720:1280"]},
            "durations": {"text_to_video": [5, 10]},
        },
    )
    task_id = asyncio.run(
        adapter.create_generation("A calm office at dawn", duration_seconds=7, aspect_ratio="9:16")
    )
    assert task_id == "task-1"
    assert runway_api.bodies[-1] == {
        "model": model,
        "promptText": "A calm office at dawn",
        "ratio": "720:1280",
        "duration": 5,
    }
    pending = asyncio.run(adapter.get_generation_status(task_id))
    assert pending.status == "PENDING" and pending.video_bytes is None
    runway_api.task = {
        "id": task_id,
        "status": "SUCCEEDED",
        "output": ["https://files.test/out.mp4?sig=1"],
    }
    done = asyncio.run(adapter.get_generation_status(task_id))
    assert done.status == "COMPLETED" and done.video_bytes == b"MP4BYTES"
    assert done.duration_seconds is None and done.raw_response["task_status"] == "SUCCEEDED"
    with pytest.raises(MediaProviderError):
        # The contract says this model has no image_to_video task.
        asyncio.run(adapter.create_generation("x", image_ref=b"\x89PNG\r\n\x1a\n" + b"\0" * 16))
    with pytest.raises(MediaProviderError):
        # Without a known ratio list nothing is guessed.
        asyncio.run(RunwayVideoAdapter("k", model, {}).create_generation("x"))


def test_contract_parser_reads_tasks_ratios_and_durations_per_model():
    spec = {
        "paths": {
            "/v1/text_to_video": {
                "post": {
                    "requestBody": {
                        "content": {
                            "application/json": {
                                "schema": {
                                    "oneOf": [
                                        {"$ref": "#/components/schemas/A"},
                                        {
                                            "properties": {
                                                "model": {"enum": ["m2", "m3"]},
                                                "ratio": {"enum": ["1:1"]},
                                                "duration": {
                                                    "type": "integer",
                                                    "minimum": 2,
                                                    "maximum": 10,
                                                },
                                                "referenceImages": {"type": "array"},
                                            },
                                            "required": ["model", "ratio", "referenceImages"],
                                        },
                                    ]
                                }
                            }
                        }
                    }
                }
            },
            "/v1/tasks/{id}": {"get": {}},
            "/v1/recipes/product_ad": {"post": {}},
        },
        "components": {
            "schemas": {
                "A": {
                    "properties": {
                        "model": {"const": "m1"},
                        "ratio": {"enum": ["16:9", "9:16"]},
                        "duration": {"enum": [4, 8]},
                    }
                }
            }
        },
    }
    contract = parse_model_contract(spec)
    assert contract["m1"] == {
        "tasks": ["text_to_video"],
        "ratios": {"text_to_video": ["16:9", "9:16"]},
        "durations": {"text_to_video": [4, 8]},
        "needs_references": {"text_to_video": False},
        # Whether this task may be asked what it would cost without being asked to do it.
        # Only the vendor's contract may say so: a dry-run flag the API does not declare
        # could submit a real, billed task.
        "dry_run": {"text_to_video": False},
    }
    assert contract["m2"]["durations"] == {"text_to_video": {"min": 2, "max": 10}}
    # What the model must be given besides words is part of its contract: m2 and m3 require
    # reference images, m1 does not.
    assert contract["m2"]["needs_references"] == {"text_to_video": True}
    assert contract["m3"]["needs_references"] == {"text_to_video": True}
    assert set(contract) == {"m1", "m2", "m3"}
    with pytest.raises(MediaProviderError):
        parse_model_contract([])
    assert pick_ratio(["1280:720", "720:1280"], "16:9") == "1280:720"


