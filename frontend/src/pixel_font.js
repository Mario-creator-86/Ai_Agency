export function textWidth(str, scale = 1, tracking = 1) {
  let w = 0;
  for (const ch of String(str).toUpperCase()) {
    const g = GLYPHS[ch] || GLYPHS[' '];
    w += (g[0].length + tracking) * scale;
  }
  return w - tracking * scale;
}

export function drawText(ctx, str, x, y, color, scale = 1, tracking = 1) {
  let cx = Math.round(x);
  ctx.fillStyle = color;
  for (const ch of String(str).toUpperCase()) {
    const g = GLYPHS[ch] || GLYPHS[' '];
    for (let row = 0; row < g.length; row += 1) {
      const bits = g[row];
      for (let col = 0; col < bits.length; col += 1) {
        if (bits[col] === '1') {
          ctx.fillRect(cx + col * scale, Math.round(y) + row * scale, scale, scale);
        }
      }
    }
    cx += (g[0].length + tracking) * scale;
  }
}

